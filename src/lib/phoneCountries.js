/** Convert an ISO-3166 alpha-2 like "IN" into its 🇮🇳 flag emoji. */
const flag = (iso2) =>
  iso2
    .toUpperCase()
    .split("")
    .map((c) => String.fromCodePoint(0x1f1e6 + (c.charCodeAt(0) - 65)))
    .join("");

export const PHONE_COUNTRIES = COUNTRIES.sort((a, b) =>
  a.name.localeCompare(b.name),
).map((c) => ({ ...c, flag: flag(c.iso2) }));

/** Default fallback used when nothing matches the stored country code. */
export const DEFAULT_PHONE_COUNTRY =
  PHONE_COUNTRIES.find((c) => c.iso2 === "IN") || PHONE_COUNTRIES[0];

/**
 * Look up a country by its stored value. Stored values can be either:
 *   - the ISO-2 code  ("IN"), or
 *   - the dial code   ("+91")  — legacy form, ambiguous between e.g. US/CA
 * Returns DEFAULT_PHONE_COUNTRY when nothing matches.
 */
export function findPhoneCountry(value) {
  if (!value) return DEFAULT_PHONE_COUNTRY;
  const v = String(value).trim();
  const byIso = PHONE_COUNTRIES.find(
    (c) => c.iso2.toLowerCase() === v.toLowerCase(),
  );
  if (byIso) return byIso;
  const withPlus = v.startsWith("+") ? v : `+${v.replace(/[^\d]/g, "")}`;
  const byDial = PHONE_COUNTRIES.find((c) => c.dial === withPlus);
  if (byDial) return byDial;
  return DEFAULT_PHONE_COUNTRY;
}

/**
 * Validate a local subscriber number against the chosen country's expected
 * length range. Ignores formatting characters (spaces, dashes, parens).
 */
export function isValidLocalNumber(localNumber, country) {
  const c = country || DEFAULT_PHONE_COUNTRY;
  const digits = String(localNumber || "").replace(/\D/g, "");
  return digits.length >= c.min && digits.length <= c.max;
}
